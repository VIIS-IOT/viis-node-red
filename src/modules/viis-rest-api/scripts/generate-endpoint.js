#!/usr/bin/env node

/**
 * CLI tool for generating new API endpoints
 * Usage: node generate-endpoint.js <entityName> [options]
 */

const fs = require('fs');
const path = require('path');

// Command line argument parsing
const args = process.argv.slice(2);
if (args.length === 0 || args.includes('--help') || args.includes('-h')) {
    console.log(`
VIIS REST API Endpoint Generator

Usage: node generate-endpoint.js <entityName> [options]

Arguments:
  entityName    Name of the entity (e.g., Device, Schedule, Telemetry)

Options:
  --crud        Generate full CRUD operations (default)
  --readonly    Generate only read operations (GET)
  --custom      Generate empty template for custom endpoints
  --path        Custom base path (default: /entityName.toLowerCase())
  --help, -h    Show this help message

Examples:
  node generate-endpoint.js Device
  node generate-endpoint.js Schedule --path /schedules
  node generate-endpoint.js Report --readonly
  node generate-endpoint.js CustomAPI --custom

This will generate:
  - controllers/<entity>.controller.ts
  - services/<entity>.service.ts
  - types/<entity>.types.ts
  - dto/<entity>.dto.ts
  - validators/<entity>.validator.ts
`);
    process.exit(0);
}

const entityName = args[0];
const options = {
    crud: !args.includes('--readonly') && !args.includes('--custom'),
    readonly: args.includes('--readonly'),
    custom: args.includes('--custom'),
    path: args.includes('--path') ? args[args.indexOf('--path') + 1] : `/${entityName.toLowerCase()}s`
};

console.log(`🚀 Generating API endpoint for: ${entityName}`);
console.log(`📁 Base path: ${options.path}`);
console.log(`🔧 Mode: ${options.crud ? 'CRUD' : options.readonly ? 'Read-only' : 'Custom'}`);

// File paths
const basePath = path.join(__dirname, '..');
const controllerPath = path.join(basePath, 'controllers', `${entityName.toLowerCase()}.controller.ts`);
const servicePath = path.join(basePath, 'services', `${entityName.toLowerCase()}.service.ts`);
const typesPath = path.join(basePath, 'types', `${entityName.toLowerCase()}.types.ts`);

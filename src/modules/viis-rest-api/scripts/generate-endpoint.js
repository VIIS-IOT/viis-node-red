// Templates
function generateControllerTemplate() {
    const routes = [];

    if (options.crud || options.readonly) {
        routes.push(`            {
                method: 'GET',
                path: '${options.path}',
                handler: 'list${entityName}s',
                middleware: ['auth']
            }`);

        routes.push(`            {
                method: 'GET',
                path: '${options.path}/:id',
                handler: 'get${entityName}',
                middleware: ['auth']
            }`);
    }

    if (options.crud) {
        routes.push(`            {
                method: 'POST',
                path: '${options.path}',
                handler: 'create${entityName}',
                middleware: ['auth']
            }`);

        routes.push(`            {
                method: 'PUT',
                path: '${options.path}/:id',
                handler: 'update${entityName}',
                middleware: ['auth']
            }`);

        routes.push(`            {
                method: 'DELETE',
                path: '${options.path}/:id',
                handler: 'delete${entityName}',
                middleware: ['auth']
            }`);
    }

    return `/**
 * @fileoverview ${entityName} controller - Generated by VIIS API Generator
 */

import { Request, Response } from 'express';
import { Inject } from 'typedi';
import { BaseController } from './base.controller';
import { Controller } from '../decorators/controller.decorator';
import { RouteDefinition } from '../types/common.types';
import { ${entityName}Service } from '../services/${entityName.toLowerCase()}.service';
import { ${entityName}Validator } from '../validators/${entityName.toLowerCase()}.validator';
import { Node } from 'node-red';
import { ApiConfigManager } from '../config/api.config';

@Controller('${options.path}')
export class ${entityName}Controller extends BaseController {
    constructor(
        @Inject() private ${entityName.toLowerCase()}Service: ${entityName}Service,
        @Inject() private ${entityName.toLowerCase()}Validator: ${entityName}Validator,
        @Inject('node') node: Node,
        @Inject('configManager') configManager: ApiConfigManager
    ) {
        super(node, configManager);
    }

    getRoutes(): RouteDefinition[] {
        return [
${routes.join(',\n')}
        ];
    }

${generateHandlerMethods()}
}`;
}

function generateHandlerMethods() {
    let methods = '';

    if (options.crud || options.readonly) {
        methods += `
    /**
     * List ${entityName.toLowerCase()}s
     */
    list${entityName}s = this.asyncHandler(async (req: Request, res: Response): Promise<void> => {
        const { page, limit, offset } = this.getPaginationParams(req);
        
        const result = await this.executeOperation(
            'list${entityName}s',
            () => this.${entityName.toLowerCase()}Service.list({ page, limit, offset })
        );
        
        this.success(res, result, 200, '${entityName}s retrieved successfully');
    }, 'list${entityName}s');

    /**
     * Get ${entityName.toLowerCase()} by ID
     */
    get${entityName} = this.asyncHandler(async (req: Request, res: Response): Promise<void> => {
        const { id } = req.params;
        this.validateString(id, 'id');
        
        const result = await this.executeOperation(
            'get${entityName}',
            () => this.${entityName.toLowerCase()}Service.getById(id)
        );
        
        if (!result) {
            return this.notFoundError(res, '${entityName} not found');
        }
        
        this.success(res, result, 200, '${entityName} retrieved successfully');
    }, 'get${entityName}');`;
    }

    if (options.crud) {
        methods += `

    /**
     * Create new ${entityName.toLowerCase()}
     */
    create${entityName} = this.asyncHandler(async (req: Request, res: Response): Promise<void> => {
        const data = await this.${entityName.toLowerCase()}Validator.validateCreate(req.body);
        
        const result = await this.executeOperation(
            'create${entityName}',
            () => this.${entityName.toLowerCase()}Service.create(data)
        );
        
        this.success(res, result, 201, '${entityName} created successfully');
    }, 'create${entityName}');

    /**
     * Update ${entityName.toLowerCase()}
     */
    update${entityName} = this.asyncHandler(async (req: Request, res: Response): Promise<void> => {
        const { id } = req.params;
        this.validateString(id, 'id');
        
        const data = await this.${entityName.toLowerCase()}Validator.validateUpdate(req.body);
        
        const result = await this.executeOperation(
            'update${entityName}',
            () => this.${entityName.toLowerCase()}Service.update(id, data)
        );
        
        this.success(res, result, 200, '${entityName} updated successfully');
    }, 'update${entityName}');

    /**
     * Delete ${entityName.toLowerCase()}
     */
    delete${entityName} = this.asyncHandler(async (req: Request, res: Response): Promise<void> => {
        const { id } = req.params;
        this.validateString(id, 'id');
        
        await this.executeOperation(
            'delete${entityName}',
            () => this.${entityName.toLowerCase()}Service.delete(id)
        );
        
        this.success(res, { message: '${entityName} deleted successfully' }, 200);
    }, 'delete${entityName}');`;
    }

    if (options.custom) {
        methods += `
    /**
     * Custom endpoint example
     * TODO: Implement your custom logic here
     */
    customEndpoint = this.asyncHandler(async (req: Request, res: Response): Promise<void> => {
        // TODO: Add your custom logic here
        this.success(res, { message: 'Custom endpoint for ${entityName}' });
    }, 'customEndpoint');`;
    }

    return methods;
}

